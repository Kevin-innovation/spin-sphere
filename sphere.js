#!/usr/bin/env node
/**
 * ============================================================================
 *  회전하는 ASCII 구(sphere) — 수학으로 그리는 3D
 * ============================================================================
 *
 *  실행:  node sphere.js            (종료: Ctrl+C)
 *         node sphere.js --reverse  (배경이 흰색인 터미널용)
 *
 *  이 프로그램은 3D 엔진도, 그래픽 라이브러리도 쓰지 않습니다.
 *  화면의 문자 한 칸마다 "이 위치에서 구가 보이는가? 보인다면 얼마나 밝은가?"
 *  를 수학으로 직접 계산해서 문자 하나를 고릅니다.
 *
 *  이런 방식을 셰이더(shader) 방식이라고 부릅니다.
 *  실제 GPU도 똑같은 일을 합니다 — 픽셀 하나하나에 같은 함수를 돌리는 것.
 *  단지 GPU는 수백만 개를 동시에, 우리는 문자 2천 개를 순서대로 할 뿐입니다.
 *
 *  전체 흐름:
 *    (1) 화면 좌표(col,row)  →  수학 좌표(x,y)          [좌표 정규화]
 *    (2) 이 (x,y)에 구가 있나?                          [구의 방정식]
 *    (3) 있다면 그 지점이 어느 방향을 보고 있나?         [법선벡터]
 *    (4) 광원 방향과 얼마나 맞닿아 있나?                 [내적 · 램버트 법칙]
 *    (5) 밝기를 색으로, 색을 문자로                      [양자화]
 *    (6) 시간에 따라 광원을 회전시켜 다시 그리기          [삼각함수 · 애니메이션]
 *
 * ----------------------------------------------------------------------------
 *  【먼저 알아야 할 용어와 약자】 — 아래 주석에 계속 나오는 말들
 * ----------------------------------------------------------------------------
 *
 *  ■ 스칼라(scalar)  ←→  벡터(vector)
 *    스칼라 = "크기만 있고 방향이 없는 값". 그냥 숫자 하나입니다.
 *      예) 온도 25도, 밝기 0.7, 시간 3초
 *    벡터 = "크기와 방향을 함께 가진 값". 숫자 여러 개를 묶은 것.
 *      예) 위치 (3, 4, 5), 색 (R, G, B), 빛이 오는 방향 (1.4, 1, 0.2)
 *
 *    - 스칼라 곱(scalar multiplication): 벡터 전체에 숫자 하나를 곱하는 것.
 *        (1, 2, 3) × 0.5 = (0.5, 1, 1.5)
 *        → 방향은 그대로, 길이만 절반. 색에 적용하면 "색조는 유지, 밝기만 감소".
 *    - 벡터 합(vector addition): 같은 자리끼리 더하는 것.
 *        (1, 2, 3) + (0.2, 0.1, 0) = (1.2, 2.1, 3)
 *    - 내적(dot product, ·): 벡터 두 개를 넣으면 스칼라 하나가 나오는 연산.
 *        (a1,a2,a3) · (b1,b2,b3) = a1·b1 + a2·b2 + a3·b3
 *        → 자세한 의미는 아래 [수학 7]에서 설명합니다.
 *
 *    이 코드에서 벡터는 전부 그냥 숫자 3개(x, y, z 또는 r, g, b)로 풀어서
 *    씁니다. 라이브러리를 안 쓰기 위해서입니다. 원본 데모는 three.js의
 *    Vector3 클래스를 썼지만 계산 내용은 완전히 동일합니다.
 *
 *  ■ 자주 나오는 약자
 *    RGB   Red, Green, Blue — 빛의 삼원색. 색을 이 3개 숫자로 표현합니다.
 *    FPS   Frames Per Second — 초당 화면을 몇 번 다시 그리는가.
 *    RAMP  '경사로'. 어두운 문자 → 밝은 문자로 완만하게 올라가는 문자열.
 *          (전문 용어로는 ASCII ramp / gray ramp / 밝기 계조라고 부릅니다.)
 *    NDC   Normalized Device Coordinates — 정규화 장치 좌표.
 *          화면 크기와 무관하게 항상 -1 ~ +1 범위를 쓰는 좌표계.
 *    ANSI  American National Standards Institute. 여기서는 터미널을 제어하는
 *          특수 문자열 규격(ANSI escape code)을 가리킵니다.
 *    HDR   High Dynamic Range — 0~1을 넘는 밝기까지 다루는 방식.
 *    uTime 원본 셰이더의 변수명. 'u'는 uniform(모든 픽셀이 공유하는 값)의 약자.
 *    vPos  'v'는 varying(픽셀마다 달라지는 값), Pos는 position(위치).
 *          → 즉 "픽셀마다 다른 위치값". 이 코드에서는 x, y가 그 역할입니다.
 *    diffuse  난반사(亂反射). 표면에서 사방으로 흩어지는 빛. 물체의 기본 명암.
 *    ambient  환경광. 어디서 오는지 특정할 수 없이 깔려 있는 은은한 빛.
 * ============================================================================
 */

// ────────────────────────────────────────────────────────────────────────────
//  0. 설정값 (상수)
// ────────────────────────────────────────────────────────────────────────────

/**
 * 밝기 램프(ramp): 왼쪽이 가장 어둡고 오른쪽이 가장 밝은 문자.
 *
 * 왜 이 순서일까? 문자가 차지하는 "잉크의 양"이 곧 밝기이기 때문입니다.
 *   ' ' 은 아무것도 안 칠함 → 가장 어두움
 *   '.' 은 점 하나          → 조금 밝음
 *   '@' 은 거의 꽉 참       → 가장 밝음
 * 즉 문자를 '픽셀의 밝기 단계'로 재활용하는 것입니다.
 *
 * 검은 배경 터미널 기준입니다. 흰 배경이면 밝기가 반대로 보이므로
 * --reverse 옵션으로 뒤집습니다.
 */
const RAMP = ' .:-~=+*#%@';

/** 초당 프레임 수. 30이면 1초에 30번 화면을 다시 그립니다. */
const FPS = 30;

/**
 * 터미널 글자는 정사각형이 아닙니다. 보통 세로가 가로의 약 2배입니다.
 * 이 값을 보정하지 않으면 구가 세로로 길쭉한 타원으로 보입니다.
 * (가로로 2배 더 많은 칸을 써야 눈에는 정사각형으로 보임)
 */
const CHAR_ASPECT = 2;

/**
 * 빛의 색과 환경광의 색을 RGB 벡터로 표현합니다. 순서는 [R, G, B].
 *
 *   SKY   : 하늘에서 내려오는 직사광. 파랑(B=1.5)이 가장 세서 차가운 느낌.
 *   GROUND: 땅에 반사되어 은은하게 깔리는 환경광(ambient).
 *           빨강(0.2)이 가장 세서 따뜻한 느낌 — 흙/모래의 반사색을 흉내.
 *
 * 값이 1을 넘어도 됩니다(1.5). 최종 단계에서 0~1로 잘라내기 때문에
 * "이 색은 쉽게 포화된다"는 뜻이 됩니다. HDR과 같은 발상입니다.
 */
const SKY = [0.5, 0.85, 1.5];
const GROUND = [0.2, 0.1, 0.05];

// ────────────────────────────────────────────────────────────────────────────
//  1. 도우미 함수
// ────────────────────────────────────────────────────────────────────────────

/**
 * 값을 0~1 범위로 자릅니다(클램핑).
 *
 * 왜 필요한가: 계산 결과가 물리적으로 불가능한 값이 될 수 있습니다.
 *   - 음수 밝기 = "어둠을 뿜는 빛" → 존재하지 않음
 *   - 1 초과    = 화면이 표현할 수 있는 최대치를 넘음
 * 수학적으로는 clamp(v) = min(1, max(0, v)) 입니다.
 */
const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);

// --reverse 옵션이면 램프를 뒤집어 미리 만들어 둡니다.
// 프레임마다 문자열을 새로 만들면 초당 수만 번 낭비이므로 딱 한 번만 계산.
const ACTIVE_RAMP = process.argv.includes('--reverse')
  ? [...RAMP].reverse().join('')
  : RAMP;

/**
 * RGB 색 하나 → ASCII 문자 한 개.  (원본 데모의 b2ASCII 함수를 옮긴 것)
 * b2ASCII 라는 이름은 "brightness to ASCII" = "밝기를 ASCII로"의 줄임말입니다.
 *
 * 이 함수는 두 단계로 나뉩니다: ① 휘도 계산  ② 램프 인덱싱
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ① 휘도(輝度, luminance) 계산 — 색 3개를 밝기 1개로 압축하기
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 문제: 우리에겐 R, G, B 세 개의 숫자가 있는데, 골라야 할 문자는 하나뿐입니다.
 *       세 개를 하나로 줄여야 합니다.
 *
 * 가장 단순한 답은 산술평균입니다:  (R + G + B) / 3
 * 그런데 이건 틀립니다. 사람의 눈이 색마다 밝기를 다르게 느끼기 때문입니다.
 *
 *   순수한 초록 (0, 1, 0) 과 순수한 파랑 (0, 0, 1) 을 나란히 놓으면
 *   초록이 훨씬 밝게 보입니다. 눈의 원추세포가 초록 파장(약 555nm) 근처에
 *   가장 민감하고, 파랑 파장에는 훨씬 둔감하기 때문입니다.
 *
 * 그래서 국제 표준(ITU-R Rec.709, HDTV·sRGB가 쓰는 규격)은 이 민감도를
 * 가중치로 만들어 놓았습니다:
 *
 *      Y = 0.2126·R + 0.7152·G + 0.0722·B
 *      ─          ──────       ──────       ──────
 *      휘도        빨강 21%     초록 72%     파랑 7%
 *
 * 여기서 Y는 휘도의 관례적 기호입니다. 가중치 세 개를 더하면
 *      0.2126 + 0.7152 + 0.0722 = 1.0000
 * 정확히 1이 됩니다. 이건 우연이 아니라 필수 조건입니다.
 * 합이 1이어야 흰색 (1,1,1)을 넣었을 때 Y = 1 (최대 밝기)이 나오고,
 * 검정 (0,0,0)을 넣으면 Y = 0 이 나와 범위가 딱 맞습니다.
 *
 * 계산 예시 — 이 프로그램에서 가장 밝은 지점 근처의 색:
 *      R=0.45, G=0.53, B=0.80  일 때
 *      Y = 0.2126×0.45 + 0.7152×0.53 + 0.0722×0.80
 *        = 0.0957      + 0.3791      + 0.0578
 *        = 0.5326
 *   → 파랑(0.80)이 제일 큰 값인데도 기여는 0.0578로 가장 작고,
 *     초록이 0.53밖에 안 되는데 기여는 0.3791로 압도적입니다.
 *     이게 "단순 평균이 아니라 가중 평균을 쓰는 이유"입니다.
 *     (참고: 단순 평균이었다면 (0.45+0.53+0.80)/3 = 0.593 — 더 밝게 나옵니다)
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ② 램프 인덱싱 — 0~1 사이의 실수를 문자 하나로 바꾸기
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 【인덱싱(indexing)이란?】
 * 인덱스(index)는 '색인·번호'라는 뜻이고, 인덱싱은 "번호로 꺼내오기"입니다.
 * 문자열이나 배열은 각 칸에 0번부터 번호가 매겨져 있고, 대괄호로 꺼냅니다:
 *
 *      RAMP = " .:-~=+*#%@"
 *      번호     0123456789…
 *
 *      RAMP[0]  → ' '   (공백,   가장 어두움)
 *      RAMP[1]  → '.'
 *      RAMP[5]  → '='
 *      RAMP[10] → '@'   (가장 밝음)
 *
 * 번호가 1이 아니라 0부터 시작하는 것을 0-based index(0 기반 색인)라고
 * 부릅니다. JavaScript, C, Python 등 대부분의 언어가 이 방식입니다.
 * 그래서 문자가 11개면 유효한 번호는 0~10 이고, 11은 범위 밖(undefined)입니다.
 *
 * 【그럼 Y를 몇 번으로 바꿔야 하나?】
 * Y는 0~1 사이의 연속된 실수(0.5326 같은 것)이고, 번호는 0~10의 정수입니다.
 * 연속된 값을 띄엄띄엄한 단계로 바꾸는 것을 양자화(quantization)라고 합니다.
 * 아날로그를 디지털로 바꿀 때 항상 하는 일입니다.
 *
 *      index = round( Y × (문자 개수 − 1) )
 *
 * ▸ 왜 (문자 개수 − 1)을 곱하나?
 *   문자가 11개일 때 그냥 11을 곱하면 Y=1에서 index=11 → 범위 밖!
 *   마지막 번호는 10이므로 10을 곱해야 Y=1이 정확히 마지막 칸을 가리킵니다.
 *   일반화하면 "0부터 N−1까지 N칸에 0~1을 펼치려면 (N−1)을 곱한다".
 *
 * ▸ 왜 round(반올림)를 쓰나?
 *   내림(floor)을 쓰면 Y=0.99일 때 index=9.9→9가 되어 가장 밝은 '@'가
 *   Y가 정확히 1.0일 때만 나옵니다. 반올림하면 각 문자가 똑같은 폭
 *   (1/10 = 0.1)의 구간을 공평하게 담당합니다.
 *
 * 계산 예시 — 위에서 구한 Y = 0.5326:
 *      0.5326 × 10 = 5.326  →  round → 5  →  RAMP[5] = '='
 *
 * 구간표 (문자 11개 기준):
 *      Y 0.00~0.05 → ' '      Y 0.45~0.55 → '='
 *      Y 0.05~0.15 → '.'      Y 0.55~0.65 → '+'
 *      Y 0.15~0.25 → ':'      Y 0.65~0.75 → '*'
 *      Y 0.25~0.35 → '-'      Y 0.75~0.85 → '#'
 *      Y 0.35~0.45 → '~'      Y 0.85~0.95 → '%'
 *                             Y 0.95~1.00 → '@'
 *
 * 문자를 늘리면(예: 32개) 더 부드러운 그라데이션이, 줄이면(예: 4개) 판화
 * 같은 거친 느낌이 나옵니다. 이것이 화면의 '해상도'가 아니라 '계조(階調)'를
 * 바꾸는 것입니다.
 */
function brightnessToChar(r, g, b) {
  // ① 휘도: RGB 3개 → 밝기 1개 (가중 평균 후 0~1로 자르기)
  const luminance = clamp01(0.2126 * r + 0.7152 * g + 0.0722 * b);

  // ② 램프 인덱싱: 0~1 실수 → 0~(길이-1) 정수 → 문자
  const index = Math.round(luminance * (ACTIVE_RAMP.length - 1));

  return ACTIVE_RAMP[index];
}

// ────────────────────────────────────────────────────────────────────────────
//  2. 한 프레임 그리기 — 이 프로그램의 심장
// ────────────────────────────────────────────────────────────────────────────

/**
 * @param {number} uTime  프로그램 시작 후 흐른 시간 (밀리초)
 * @param {number} cols   터미널 가로 칸 수
 * @param {number} rows   터미널 세로 줄 수
 * @returns {string}      완성된 한 화면 (줄바꿈으로 이어붙인 문자열)
 */
function frame(uTime, cols, rows) {
  // ── 2-1. 광원의 위치를 시간으로 계산 ────────────────────────────────────
  //
  // 【수학 3: 원의 매개변수 방정식】
  // 반지름 r인 원 위의 점은 각도 θ 하나로 표현됩니다:
  //
  //      x = r·cos θ ,  z = r·sin θ
  //
  // θ를 시간에 따라 조금씩 키우면 그 점이 원을 따라 돕니다. 그게 회전입니다.
  // cos²θ + sin²θ = 1 (피타고라스 항등식) 이므로 √(x²+z²) = r 로 항상 일정 —
  // 즉 광원은 절대 가까워지거나 멀어지지 않고 정확히 원을 그립니다.
  //
  // 400으로 나누는 이유: uTime은 밀리초라 그냥 쓰면 초당 수백 바퀴를 돕니다.
  //   θ = t/400 → 한 바퀴(2π) 도는 데 약 2513ms ≈ 2.5초.
  //   숫자를 키우면 느려지고, 줄이면 빨라집니다.
  const theta = uTime / 400;

  // 반지름을 √2로 잡은 이유는 아래 2-4에서 설명합니다.
  const r = Math.SQRT2;
  const lightX = Math.cos(theta) * r;
  const lightZ = Math.sin(theta) * r;
  const lightY = 1; // 높이는 고정 → 광원이 머리 위 비스듬한 궤도를 돕니다.

  // ── 2-2. 구의 화면상 반지름 결정 ────────────────────────────────────────
  //
  // 가로/세로 중 작은 쪽에 맞춰야 구가 화면 밖으로 잘리지 않습니다.
  // 가로는 CHAR_ASPECT로 나눠 "실제 눈에 보이는 폭"으로 환산한 뒤 비교합니다.
  const radius = Math.min(cols / CHAR_ASPECT, rows) / 2;

  const lines = [];

  // ── 2-3. 화면의 모든 칸을 순회 ──────────────────────────────────────────
  // 이 이중 루프 안쪽이 곧 '픽셀 셰이더'입니다.
  for (let row = 0; row < rows; row++) {
    let line = '';

    for (let col = 0; col < cols; col++) {
      // 【수학 4: 좌표계 변환】
      // 터미널 좌표는 (0,0)이 왼쪽 위이고 단위가 '칸'입니다.
      // 수학 좌표는 (0,0)이 한가운데이고 구의 가장자리가 ±1이면 편합니다.
      // 그래서 세 가지를 동시에 합니다:
      //   ① 중심 이동  : (cols-1)/2 를 빼서 원점을 화면 한가운데로
      //   ② 크기 조정  : radius로 나눠서 구의 가장자리를 정확히 ±1로
      //   ③ 종횡비 보정: x만 CHAR_ASPECT로 더 나눠 글자 비율을 상쇄
      const x = (col - (cols - 1) / 2) / (radius * CHAR_ASPECT);

      // y는 부호를 뒤집습니다. 화면은 아래로 갈수록 row가 커지지만
      // 수학에서는 위로 갈수록 y가 커져야 하기 때문입니다.
      const y = -(row - (rows - 1) / 2) / radius;

      // 【수학 5: 구의 방정식과 정사영】
      // 원점 중심, 반지름 1인 단위구는  x² + y² + z² = 1  입니다.
      // (x, y)가 주어졌을 때 화면 쪽(앞면)의 z는:
      //
      //      z = √(1 − x² − y²)
      //
      // 여기서 zSquared = 1 − (x² + y²) 를 먼저 계산합니다.
      //   zSquared > 0  → 구 안쪽. 표면이 존재함
      //   zSquared ≤ 0  → 구 바깥. 배경(공백)
      //
      // 이 판정 하나가 곧 "구의 실루엣"을 만듭니다. 원의 방정식
      // x² + y² < 1 을 검사하는 것과 같으므로 윤곽선이 정확한 원이 됩니다.
      const zSquared = 1 - (x * x + y * y);

      if (zSquared <= 0) {
        line += ' '; // 구 바깥 → 배경
        continue;
      }

      const z = Math.sqrt(zSquared);

      // 【수학 6: 법선벡터 — 이 코드에서 가장 아름다운 부분】
      // 법선(normal)이란 표면이 "바라보는 방향"을 가리키는 단위벡터입니다.
      // 보통은 미분으로 구해야 하지만, 원점 중심 단위구에서는 마법처럼
      // 간단합니다:
      //
      //      표면 위 점의 위치벡터 (x, y, z)  ==  그 지점의 법선벡터
      //
      // 왜? 구의 중심에서 표면으로 그은 선은 항상 표면과 수직이기 때문입니다.
      // 게다가 x²+y²+z²=1 이므로 길이가 이미 1 — 정규화도 필요 없습니다.
      // 그래서 아래 코드에는 법선을 구하는 줄이 아예 없습니다.
      // (x, y, z)를 그대로 쓰면 됩니다.

      // 【수학 7: 내적과 램버트 코사인 법칙】
      // 두 단위벡터 A, B의 내적은  A·B = |A||B|cos θ = cos θ 입니다.
      // 즉 내적은 "두 방향이 얼마나 같은 쪽을 보는가"를 -1~1로 재는 자입니다.
      //      1  : 완전히 같은 방향  (정면으로 빛을 받음 → 가장 밝음)
      //      0  : 직각              (빛이 스쳐 지나감 → 어두움)
      //     -1  : 정반대            (뒤통수 → 빛이 안 닿음)
      //
      // 램버트(Lambert)의 코사인 법칙: 표면의 밝기는 법선과 광원 방향이
      // 이루는 각의 cos에 비례한다. 물리적으로는 빛이 비스듬히 들어올수록
      // 같은 양의 빛이 더 넓은 면적에 퍼져서 단위면적당 세기가 줄기 때문입니다.
      //
      // max(0, ...)이 꼭 필요한 이유: 내적이 음수라는 건 표면이 광원을
      // 등지고 있다는 뜻입니다. 이걸 그대로 두면 "음의 빛"이 되어 색이
      // 이상해집니다. 0으로 잘라 "빛이 안 닿음"으로 처리합니다.
      //
      // 0.5는 전체 밝기 조절 손잡이입니다.
      const dot = x * lightX + y * lightY + z * lightZ;
      const diffuse = 0.5 * Math.max(0, dot);

      // ── 2-4. 광원 벡터 길이에 대한 참고 ──────────────────────────────
      // 엄밀히 하려면 광원 벡터도 단위벡터로 정규화해야 내적이 정확한
      // cos θ가 됩니다. 여기서는 길이가
      //      √( (√2·cosθ)² + 1² + (√2·sinθ)² ) = √(2 + 1) = √3
      // 으로 회전해도 항상 일정합니다(√2를 쓴 이유가 이것 — 계산이 예뻐짐).
      // 길이가 상수이므로 정규화를 생략해도 전체 밝기가 √3배로 일정하게
      // 커질 뿐, 명암의 모양은 똑같습니다. 그래서 원본 코드도 생략했습니다.

      // 【수학 8: 색은 벡터다 — 스칼라 곱과 벡터 합】
      //
      // 최종색 = 직사광 + 환경광 = SKY × diffuse + GROUND
      //
      // 여기서 두 가지 연산이 쓰입니다.
      //
      // ▸ 스칼라 곱 (SKY × diffuse)
      //   diffuse는 방향이 없는 숫자 하나 = 스칼라입니다.
      //   SKY는 숫자 3개짜리 = 벡터입니다.
      //   벡터에 스칼라를 곱하면 '모든 성분에 똑같이' 곱해집니다:
      //
      //     (0.5, 0.85, 1.5) × 0.4 = (0.20, 0.34, 0.60)
      //
      //   세 성분의 '비율'(0.5 : 0.85 : 1.5)은 그대로 유지되고 크기만
      //   줄었습니다. 색으로 말하면 색조(hue)는 그대로, 밝기만 어두워진 것.
      //   → 그래서 구의 어두운 쪽도 같은 푸른빛을 유지합니다.
      //
      // ▸ 벡터 합 (… + GROUND)
      //   같은 자리끼리 더합니다:
      //     (0.20, 0.34, 0.60) + (0.2, 0.1, 0.05) = (0.40, 0.44, 0.65)
      //
      //   GROUND는 diffuse와 무관한 상수입니다. 즉 빛이 전혀 닿지 않아
      //   diffuse = 0 인 뒷면에서도 (0.2, 0.1, 0.05)는 남습니다.
      //   덕분에 그림자가 완전한 검정으로 뭉개지지 않고, 붉은 기가 도는
      //   어둠으로 표현됩니다. 실제 게임·영화 렌더링에서도 쓰는 기법입니다.
      const cr = SKY[0] * diffuse + GROUND[0];
      const cg = SKY[1] * diffuse + GROUND[1];
      const cb = SKY[2] * diffuse + GROUND[2];

      line += brightnessToChar(cr, cg, cb);
    }

    lines.push(line);
  }

  return lines.join('\n');
}

// ────────────────────────────────────────────────────────────────────────────
//  3. 터미널 제어와 애니메이션 루프
// ────────────────────────────────────────────────────────────────────────────
//
//  ANSI 이스케이프 코드: 터미널에게 보내는 특수 명령 문자열입니다.
//    \x1b[?25l  커서 숨기기   (깜빡이는 커서가 그림을 방해하므로)
//    \x1b[?25h  커서 되돌리기
//    \x1b[H     커서를 왼쪽 맨 위로 이동
//    \x1b[2J    화면 전체 지우기
//    \x1b[0m    색·스타일 초기화
//
//  애니메이션의 정의: "조금 바꿔서 다시 그리기"를 빠르게 반복하는 것.
//  여기서 매 프레임 바뀌는 건 단 하나 — theta(광원의 각도)뿐입니다.

// require.main === module 은 "이 파일이 직접 실행되었는가?"를 묻는 관용구입니다.
// node sphere.js 로 실행하면 참 → 애니메이션 시작.
// 다른 파일에서 require('./sphere') 로 불러오면 거짓 → 함수만 빌려 쓸 수 있습니다.
if (require.main === module) {
  const out = process.stdout;

  out.write('\x1b[?25l');

  // Ctrl+C로 껐을 때 커서가 사라진 채로 남지 않도록 반드시 되돌립니다.
  process.on('SIGINT', () => {
    out.write('\x1b[?25h\x1b[0m\n');
    process.exit(0);
  });
  process.on('exit', () => out.write('\x1b[?25h'));

  const startTime = Date.now();

  setInterval(() => {
    // 매 프레임 크기를 다시 읽습니다 → 창을 늘리면 구도 같이 커집니다.
    const cols = out.columns || 80;
    const rows = (out.rows || 24) - 1; // 마지막 한 줄은 여백(스크롤 방지)

    const elapsed = Date.now() - startTime;

    // 커서 이동 + 화면 지우기 + 새 프레임을 한 번의 write로 보냅니다.
    // 나눠서 쓰면 지워진 상태가 눈에 보여 화면이 깜빡입니다.
    out.write('\x1b[H\x1b[2J' + frame(elapsed, cols, rows));
  }, 1000 / FPS);
}

